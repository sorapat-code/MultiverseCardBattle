using System;

namespace MultiverseCardBattle.Cards
{
    /// <summary>
    /// Keyword ของการ์ด (เก็บเป็น Flags เหมือน CardTag)
    /// Silence จะล้าง Keyword ทั้งหมดของการ์ดใบนั้น
    /// </summary>
    [Flags]
    public enum Keyword
    {
        None = 0,

        // ศัตรูต้องโจมตียูนิตที่มี Taunt ก่อน
        Taunt        = 1 << 0,

        // โจมตีได้ทันทีที่ลงสนาม (ทั้งยูนิตและ Leader)
        Charge       = 1 << 1,

        // โจมตีได้ทันทีที่ลงสนาม แต่โจมตีได้เฉพาะยูนิตศัตรู
        Rush         = 1 << 2,

        // กันความเสียหายครั้งถัดไป 1 ครั้ง (True Damage ทะลุ)
        Shield       = 1 << 3,

        // ความเสียหายที่ทำได้จะฟื้น HP ให้ Leader เจ้าของ
        Lifesteal    = 1 << 4,

        // ยูนิตที่โดนความเสียหายจากการ์ดนี้จะตายทันที
        Backstab     = 1 << 5,

        // ศัตรูเลือกเป็นเป้าหมายไม่ได้ จนกว่าจะโจมตี
        Stealth      = 1 << 6,

        // โจมตีได้ 2 ครั้งต่อเทิร์น
        DoubleStrike = 1 << 7,

        // ความเสียหายส่วนเกินจากการโจมตียูนิตส่งต่อไปยัง Leader ศัตรู
        Pierce       = 1 << 8,

        // สร้างความเสียหายก่อนการโจมตีกลับ (ถ้าเป้าหมายตายก่อน จะไม่โดนโจมตีกลับ)
        QuickAttack  = 1 << 9,

        // ความเสียหายส่วนเกินจากการโจมตียูนิตกระเด็นไปยังยูนิตศัตรูข้างเคียง
        Overwhelm    = 1 << 10,

        // ไม่ถูกหยุดการโจมตีด้วย Stun / Freeze / Disarm / Confusion
        Unstoppable  = 1 << 11,

        // ขณะมียูนิต Guard อยู่ ศัตรูโจมตี Leader ของเจ้าของไม่ได้
        Guard        = 1 << 12,

        // กัน Effect ที่เลือกเป้าหมายจากศัตรูครั้งถัดไป แล้ว Ward หายไป
        Ward         = 1 << 13,

        // ไม่รับความเสียหายและสถานะเสียทุกประเภท (ยังถูก Destroy / Banish ได้)
        Immune       = 1 << 14,

        // ตายครั้งแรกแล้วกลับมาบนสนามด้วย 1 HP
        Reborn       = 1 << 15,

        // ความสามารถ Spellburst ทำงานครั้งแรกที่เจ้าของใช้การ์ด Spell แล้ว Keyword หายไป
        Spellburst   = 1 << 16,

        // ขณะเจ้าของมี Token บนสนาม: ได้ Unstoppable และยูนิตศัตรูโจมตีไม่ได้ (เลือกด้วยสเปลได้)
        Shadowbound  = 1 << 17,

        // ใส่ในเด็คได้แค่ 1 ใบ
        Unique       = 1 << 18,
        // เฉพาะ Spell: ใช้ตอบโต้การกระทำของศัตรูได้ แม้ในเทิร์นของศัตรู (เปิดหน้าต่างตอบโต้ / เชน)
        Fast         = 1 << 19,
        // ขณะ HP ไม่เต็ม ได้ Attack เพิ่ม
        Enrage       = 1 << 20,
        // สวนกลับเสมอเมื่อโดนยูนิตโจมตี แม้ตายจากการโจมตีนั้น / ผู้โจมตีมี Quick Attack / ถูกควบคุมอยู่
        Retaliate    = 1 << 21,
        // รอดจากความเสียหายครั้งแรกแล้วได้ Attack เพิ่มถาวร (ครั้งเดียว)
        Frenzy       = 1 << 22,
        // ศัตรูเลือกเป็นเป้าหมายไม่ได้ ขณะเจ้าของมียูนิตอื่นที่ไม่ใช่ Elusive
        Elusive      = 1 << 23,
        // ฟื้น HP ตัวเองตอนเริ่มเทิร์นของเจ้าของ
        Regenerate   = 1 << 24,
        // ถูกยูนิตโจมตีแล้วสะท้อนความเสียหายกลับ ไม่ว่าจะตายหรือไม่
        Thorns       = 1 << 25,
        // ความเสียหายที่ทำกับยูนิตแล้วเป้าหมายเหลือ HP น้อยพอ จะตายทันที
        LethalStrike = 1 << 26,
        // ลงการ์ดแล้ว Energy ของเทิร์นหน้าถูกล็อกบางส่วน
        Overload     = 1 << 27,
        // ใช้แล้วได้สำเนา (ไม่มี Echo) กลับเข้ามือ 1 ใบ
        Echo         = 1 << 28
    }
}
